"""
Test-only mocks for generated ROS2 message modules.

The local_planner code imports message types from `movement_interfaces.msg`
and `system_interfaces.msg` (generated by rosidl at colcon-build time) purely
for `to_msg`/`from_msg` (de)serialization helpers. None of the local_planner
unit tests exercise that (de)serialization path, so we stub the modules out
here rather than requiring a full ROS2 build environment to run these tests.
"""

